/**
 * Total expected chapter count in canonical Protestant Bible
 * Old Testament: 929 chapters
 * New Testament: 260 chapters
 * Total: 1,189 chapters
 */
export const TOTAL_CANONICAL_CHAPTERS = BIBLE_BOOKS_MAPPING.reduce(
  (acc, b) => acc + b.total_chapters, 
  0
);

export function getBookByNumber(bookNumber: number): BibleBook | undefined {
  return BIBLE_BOOKS_MAPPING.find(b => b.book_number === bookNumber);
}

export function getBookById(id: string): BibleBook | undefined {
  return BIBLE_BOOKS_MAPPING.find(b => b.id === id);
}

export function getBookByName(name: string): BibleBook | undefined {
  const q = name.toLowerCase().trim();
  return BIBLE_BOOKS_MAPPING.find(
    b => b.english_name.toLowerCase() === q || b.urdu_name.trim() === name.trim()
  );
}

export function getChapterUrl(folderCode: string, chapterNumber: number): string {
  return `${WORDPOCKET_BASE_URL}/${folderCode}/${chapterNumber}.htm`;
}
